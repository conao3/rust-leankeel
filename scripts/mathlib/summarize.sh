#!/usr/bin/env bash
# Usage: summarize.sh IN.jsonl OUTDIR [CONFIG]
# Sorts the per-file records of measure.sh into OUTDIR/files.jsonl and writes the totals to
# OUTDIR/summary.json and OUTDIR/summary.md. CONFIG is the configuration measure.sh ran with.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
. "$here/env.sh"
in=${1:?usage: summarize.sh IN.jsonl OUTDIR}
outdir=${2:?usage: summarize.sh IN.jsonl OUTDIR [CONFIG]}
config=${3:-}
mkdir -p "$outdir"
jq -cs 'sort_by(.Path) | .[]' "$in" >"$outdir/files.jsonl.tmp"
mv "$outdir/files.jsonl.tmp" "$outdir/files.jsonl"

options=$(if [ -n "$config" ]; then sed -n '/^\[lean-options\]/,/^\[/{/^"/p}' "$config"; fi)
jq -s --arg options "$options" --arg tag "$MATHLIB_TAG" --arg commit "$MATHLIB_COMMIT" --arg rules "$MATHLIB_RULES" '
  def rate(a; r): if a + r == 0 then null else (a * 10000 / (a + r) | round / 100) end;
  (map(select(has("Error") | not))) as $ok
  | ([$ok[] | .Applied[]] | length) as $applied
  | ([$ok[] | .Rejected[]] | length) as $rejected
  | {Mathlib: {Tag: $tag, Commit: $commit},
     FixRules: ($rules | split(" ")),
     LeanOptions: ($options | split("\n") | map(select(. != ""))),
     Files: length,
     Analyzed: ($ok | length),
     Failed: (map(select(has("Error"))) | length),
     TimedOut: (map(select(.Exit == 124)) | length),
     FilesChanged: ($ok | map(select(.Applied | length > 0)) | length),
     FilesWithRejected: ($ok | map(select(.Rejected | length > 0)) | length),
     Fixes: {Attempted: ($applied + $rejected), Applied: $applied, Rejected: $rejected,
             ApplicationRatePercent: rate($applied; $rejected)},
     FixesByRule: ([$ok[] | (.Applied[] | {Rule, A: 1, R: 0}), (.Rejected[] | {Rule, A: 0, R: 1})]
       | group_by(.Rule)
       | map({Rule: .[0].Rule, Applied: (map(.A) | add), Rejected: (map(.R) | add),
              ApplicationRatePercent: rate(map(.A) | add; map(.R) | add)})),
     RemainingDiagnostics: ([$ok[] | .Path as $p | .Diagnostics[] | . + {Path: $p}]
       | group_by([.Rule, .Level])
       | map({Rule: .[0].Rule, Level: .[0].Level, Count: (map(.Count) | add),
              Files: (map(.Path) | unique | length)})
       | sort_by(-.Count, .Rule))}
' "$outdir/files.jsonl" >"$outdir/summary.json"

jq -r '
  def n: if . == null then "n/a" else tostring end;
  "# Leankeel fix application rate on Mathlib",
  "",
  "Generated by `scripts/mathlib/summarize.sh` from `files.jsonl`; do not edit by hand.",
  "",
  "Mathlib \(.Mathlib.Tag) (`\(.Mathlib.Commit)`), every `Mathlib/**/*.lean` file, `leankeel source fix-source --rules \(.FixRules | join(" "))`.",
  "",
  "Extra Lean options: \(if .LeanOptions == [] then "none" else (.LeanOptions | map("`\(.)`") | join(", ")) end).",
  "",
  "| Measure | Value |",
  "| --- | ---: |",
  "| Files | \(.Files) |",
  "| Analyzed | \(.Analyzed) |",
  "| Failed | \(.Failed) |",
  "| Timed out | \(.TimedOut) |",
  "| Files changed | \(.FilesChanged) |",
  "| Files with a rejected fix | \(.FilesWithRejected) |",
  "| Fixes attempted | \(.Fixes.Attempted) |",
  "| Fixes applied | \(.Fixes.Applied) |",
  "| Fixes rejected | \(.Fixes.Rejected) |",
  "| Application rate (%) | \(.Fixes.ApplicationRatePercent | n) |",
  "",
  "## Fixes by rule",
  "",
  "| Rule | Applied | Rejected | Application rate (%) |",
  "| --- | ---: | ---: | ---: |",
  (.FixesByRule[] | "| `\(.Rule)` | \(.Applied) | \(.Rejected) | \(.ApplicationRatePercent | n) |"),
  "",
  "## Diagnostics left after fixing",
  "",
  "| Rule | Level | Count | Files |",
  "| --- | --- | ---: | ---: |",
  (.RemainingDiagnostics[] | "| `\(.Rule)` | \(.Level) | \(.Count) | \(.Files) |")
' "$outdir/summary.json" >"$outdir/summary.md"
